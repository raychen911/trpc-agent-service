#!/usr/bin/env sh
# ===================================================================
# gate-check.sh - 提交/交付前质量门禁（Spec 驱动开发的"自动监理"）
# ===================================================================
# 说明: 依次执行 flake8 静态检查 + 全量单元测试与覆盖率（复用
#   lint_flake8.sh / coverage.sh）。任一步失败立即退出（非零），
#   门禁未通过时禁止提交与部署（见 .agent/spec-driven-dev）。
# 用法: bash gate-check.sh
# ===================================================================

cd "$(dirname "$0")"

step() { echo ""; echo "=== [gate] $1 ==="; }

step "1/2 flake8 静态检查"
sh ./lint_flake8.sh || { echo "[gate] ❌ 静态检查未通过，先修复再继续"; exit 1; }

step "2/2 单元测试 + 覆盖率"
sh ./coverage.sh || { echo "[gate] ❌ 测试/覆盖率未通过，先修复再继续"; exit 1; }

step "✅ 门禁通过：lint + 测试 + 覆盖率 OK，可以提交/交付"
