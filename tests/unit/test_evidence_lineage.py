def test_release_binding_is_required_and_compared_without_exposing_nonce(
    tmp_path, monkeypatch
) -> None:
    monkeypatch.delenv("TRPC_RELEASE_ID", raising=False)
    monkeypatch.delenv("TRPC_RELEASE_NONCE", raising=False)
    current = source_fingerprint(tmp_path, ())
    evidence = build_evidence(
        root=tmp_path,
        producer="tests.evidence_lineage",
        runtime=_runtime(),
        source_roots=(),
    )

    assert validate_release_binding(evidence) == ["production evidence release_binding is missing"]
    with pytest.raises(ValueError, match="TRPC_RELEASE_ID and TRPC_RELEASE_NONCE"):
        current_release_binding(required=True)

    monkeypatch.setenv("TRPC_RELEASE_ID", "release-evidence-test")
    release_nonce = "r" * 32
    monkeypatch.setenv("TRPC_RELEASE_NONCE", release_nonce)
    expected = current_release_binding(required=True)
    assert expected is not None
    bound = build_evidence(
        root=tmp_path,
        producer="tests.evidence_lineage",
        runtime=_runtime(),
        source_roots=(),
    )
    assert validate_current_candidate_evidence(bound, current_source=current) == []
    assert release_nonce not in str(bound)

    mismatched = dict(bound)
    mismatched["release_binding"] = {
        "release_id": "release-other",
        "nonce_sha256": expected["nonce_sha256"],
    }
    assert validate_release_binding(mismatched, expected=expected) == [
        "production evidence release_id does not match expected release"
    ]
