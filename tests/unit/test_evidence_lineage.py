def test_evidence_validation_rejects_missing_stale_future_and_mismatched_lineage(
    tmp_path, monkeypatch
) -> None:
    monkeypatch.setenv("TRPC_RELEASE_ID", "release-evidence-test")
    monkeypatch.setenv("TRPC_RELEASE_NONCE", "r" * 32)
    current = source_fingerprint(tmp_path, ())
    now = datetime(2026, 8, 22, 12, 0, tzinfo=UTC)
    valid = build_evidence(
        root=tmp_path,
        producer="tests.evidence_lineage",
        run_id="valid-evidence-run",
        generated_at=now,
        runtime=_runtime(),
        source_roots=(),
    )

    assert validate_current_candidate_evidence(valid, current_source=current, now=now) == []
    assert validate_current_candidate_evidence({}, current_source=current, now=now)

    missing_nonce = dict(valid)
    missing_nonce.pop("run_nonce")
    assert (
        validate_current_candidate_evidence(missing_nonce, current_source=current, now=now)[0]
        == "production evidence run_nonce is missing or invalid"
    )

    stale = dict(valid)
    stale["generated_at"] = (now - timedelta(seconds=DEFAULT_EVIDENCE_TTL_SECONDS + 1)).isoformat()
    assert (
        "expired" in validate_current_candidate_evidence(stale, current_source=current, now=now)[0]
    )

    future = dict(valid)
    future["generated_at"] = (now + timedelta(seconds=1)).isoformat()
    assert (
        "future" in validate_current_candidate_evidence(future, current_source=current, now=now)[0]
    )

    mismatch = dict(valid)
    mismatch["source_fingerprint"] = {
        "algorithm": "sha256",
        "status": "available",
        "value": "0" * 64,
    }
    assert (
        "different candidate"
        in validate_current_candidate_evidence(mismatch, current_source=current, now=now)[0]
    )


