def _runtime() -> dict[str, object]:
    return runtime_fingerprint(
        mode="real_postgresql_redis_multiprocess",
        worker_identities=[{"pid": 11, "container_id": "worker-a"}],
        stream="trpc:inbound:v1",
        group="trpc-workers-v1",
        parameters={"callbacks": 200, "burst_turns": 200},
    )


