def _kubernetes_configuration(args: argparse.Namespace | None = None) -> dict[str, Any]:
    """Validate the read-only Kubernetes inspection configuration.

    A Kubernetes performance run must name its namespace and context.  The
    kubeconfig may be supplied through the dedicated performance variable or
    the standard ``KUBECONFIG`` variable used by the operator.  No implicit
    Docker or host-process discovery is allowed on this path.
    """

    def value(name: str, fallback: str | None = None) -> str:
        raw = getattr(args, name, None) if args is not None else None
        if raw is None:
            return (fallback or "").strip()
        return str(raw).strip()

    namespace = value("kubernetes_namespace", os.getenv(KUBERNETES_NAMESPACE_ENV))
    context = value("kubernetes_context", os.getenv(KUBERNETES_CONTEXT_ENV))
    kubeconfig = value(
        "kubernetes_kubeconfig",
        os.getenv(KUBERNETES_KUBECONFIG_ENV) or os.getenv("KUBECONFIG"),
    )
    expected_image = value(
        "kubernetes_image_digest",
        os.getenv(KUBERNETES_IMAGE_DIGEST_ENV) or os.getenv("TRPC_REAL_IMAGE_DIGEST"),
    ).lower()
    expected_source = value(
        "kubernetes_source_fingerprint",
        os.getenv(KUBERNETES_SOURCE_FINGERPRINT_ENV),
    ).lower()
    memory_limit_raw = getattr(args, "kubernetes_memory_limit_bytes", None) if args else None
    if memory_limit_raw is None:
        memory_limit_raw = os.getenv(KUBERNETES_MEMORY_LIMIT_ENV)
    memory_limit: int | None = None
    if memory_limit_raw not in (None, ""):
        try:
            memory_limit = int(str(memory_limit_raw))
        except (TypeError, ValueError) as error:
            raise ValueError("Kubernetes memory limit must be an integer") from error
        if memory_limit <= 0 or memory_limit >= 2**60:
            raise ValueError("Kubernetes memory limit must be within (0, 2**60)")

    if _KUBERNETES_NAMESPACE_RE.fullmatch(namespace) is None:
        raise ValueError("Kubernetes performance namespace is invalid or missing")
    if _KUBERNETES_CONTEXT_RE.fullmatch(context) is None:
        raise ValueError("Kubernetes performance context is invalid or missing")
    if kubeconfig and (len(kubeconfig) > 4096 or any(char in kubeconfig for char in "\x00\r\n")):
        raise ValueError("Kubernetes performance kubeconfig path is invalid")
    if expected_image and _IMAGE_DIGEST_RE.fullmatch(expected_image) is None:
        raise ValueError("Kubernetes expected image must be a sha256 digest")
    if expected_source and _KUBERNETES_FINGERPRINT_RE.fullmatch(expected_source) is None:
        raise ValueError("Kubernetes expected source fingerprint is invalid")
    return {
        "namespace": namespace,
        "context": context,
        "kubeconfig": kubeconfig,
        "expected_image_digest": expected_image or None,
        "expected_source_fingerprint": expected_source or None,
        "memory_limit_bytes": memory_limit,
    }


def _canonical_json(value: Any) -> str:
    """Serialize evidence deterministically before hashing or signing it."""

    try:
        return json.dumps(
            value,
            ensure_ascii=True,
            allow_nan=False,
            separators=(",", ":"),
            sort_keys=True,
        )
    except (TypeError, ValueError) as error:
        raise ValueError("Kubernetes preflight evidence is not canonical JSON") from error


def _strict_json_object(value: str) -> dict[str, Any]:
    """Parse one JSON object while rejecting duplicate keys and non-finite values."""

    def reject_duplicates(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
        result: dict[str, Any] = {}
        for key, item in pairs:
            if key in result:
                raise ValueError("duplicate JSON key")
            result[key] = item
        return result

    try:
        parsed = json.loads(
            value,
            object_pairs_hook=reject_duplicates,
            parse_constant=lambda token: (_ for _ in ()).throw(
                ValueError(f"non-finite JSON value: {token}")
            ),
        )
    except (TypeError, ValueError, json.JSONDecodeError) as error:
        raise ValueError("Kubernetes preflight evidence is invalid JSON") from error
    if not isinstance(parsed, dict):
        raise ValueError("Kubernetes preflight evidence must be a JSON object")
    return parsed


def _validate_preflight_attestation(
    preflight: Mapping[str, Any],
    *,
    source_fingerprint: str,
    image_digest: str,
) -> None:
    """Check the service identity claims carried by a parent preflight."""

    if preflight.get("status") != "pass":
        raise ValueError("Kubernetes preflight status is not pass")
    if preflight.get("worker_count") != PRODUCTION_MIN_WORKERS:
        raise ValueError(f"Kubernetes preflight worker_count must equal {PRODUCTION_MIN_WORKERS}")
    if preflight.get("worker_concurrency") != PRODUCTION_WORKER_CONCURRENCY:
        raise ValueError(
            f"Kubernetes preflight worker_concurrency must equal {PRODUCTION_WORKER_CONCURRENCY}"
        )
    kubernetes = preflight.get("kubernetes")
    if (
        not isinstance(kubernetes, Mapping)
        or not isinstance(kubernetes.get("namespace"), str)
        or _KUBERNETES_NAMESPACE_RE.fullmatch(kubernetes["namespace"]) is None
        or kubernetes.get("namespace_bound") is not True
    ):
        raise ValueError("Kubernetes preflight namespace binding is invalid")
    source = preflight.get("source_fingerprint")
    if not isinstance(source, Mapping) or source.get("value") != source_fingerprint:
        raise ValueError("Kubernetes preflight source fingerprint is not bound")
    worker_attestation = preflight.get("worker_image_attestation")
    if (
        not isinstance(worker_attestation, Mapping)
        or worker_attestation.get("status") != "pass"
        or worker_attestation.get("source_fingerprint") != source_fingerprint
        or worker_attestation.get("image_id") != image_digest
    ):
        raise ValueError("Kubernetes worker image attestation is not bound")
    service_attestation = preflight.get("service_image_attestation")
    if not isinstance(service_attestation, Mapping):
        raise ValueError("Kubernetes service image attestation is missing")
    outbox_attestation = service_attestation.get("outbox-dispatcher")
    if (
        not isinstance(outbox_attestation, Mapping)
        or outbox_attestation.get("status") != "pass"
        or outbox_attestation.get("source_fingerprint") != source_fingerprint
        or outbox_attestation.get("image_id") != image_digest
    ):
        raise ValueError("Kubernetes outbox image attestation is not bound")


def build_kubernetes_preflight_evidence(
    preflight: Mapping[str, Any],
    *,
    run_id: str,
    run_token: str,
    source_fingerprint: str,
    image_digest: str,
) -> dict[str, Any]:
    """Build the signed evidence envelope consumed by an in-cluster load Job.

    The parent gate is responsible for obtaining and validating ``preflight``.
    The Job receives this envelope through a bounded file and receives the
    unshared ``run_token`` through a Secret-backed environment variable.  The
    token is never serialized into the envelope or the report.
    """

    if _KUBERNETES_RUN_ID_RE.fullmatch(run_id) is None:
        raise ValueError("Kubernetes performance run ID is invalid")
    if (
        not run_token
        or len(run_token) > 4096
        or any(ord(char) < 32 or ord(char) == 127 for char in run_token)
    ):
        raise ValueError("Kubernetes performance run token is invalid")
    source_value = source_fingerprint.strip().lower()
    image_value = image_digest.strip().lower()
    if _KUBERNETES_FINGERPRINT_RE.fullmatch(source_value) is None:
        raise ValueError("Kubernetes performance source fingerprint is invalid")
    if _IMAGE_DIGEST_RE.fullmatch(image_value) is None:
        raise ValueError("Kubernetes performance image digest is invalid")
    _validate_preflight_attestation(
        preflight,
        source_fingerprint=source_value,
        image_digest=image_value,
    )
    preflight_value = dict(preflight)
    unsigned: dict[str, Any] = {
        "schema_version": KUBERNETES_PREFLIGHT_EVIDENCE_SCHEMA_VERSION,
        "run_id": run_id,
        "source_fingerprint": source_value,
        "image_digest": image_value,
        "preflight": preflight_value,
        "preflight_sha256": hashlib.sha256(
            _canonical_json(preflight_value).encode("utf-8")
        ).hexdigest(),
        "token_sha256": hashlib.sha256(run_token.encode("utf-8")).hexdigest(),
    }
    signature = hmac.new(
        run_token.encode("utf-8"),
        _canonical_json(unsigned).encode("utf-8"),
        hashlib.sha256,
    ).hexdigest()
    return {**unsigned, "signature": signature}


def _load_kubernetes_preflight_evidence(args: argparse.Namespace) -> dict[str, Any]:
    """Load and verify parent-attested preflight evidence without using kubectl."""

    if not bool(getattr(args, "kubernetes", False)):
        raise ValueError("Kubernetes load worker requires --kubernetes")
    path_value = getattr(args, "kubernetes_preflight_evidence", None)
    if not isinstance(path_value, str) or not path_value.strip():
        raise ValueError("Kubernetes parent preflight evidence path is missing")
    path = Path(path_value)
    if path.is_symlink():
        raise ValueError("Kubernetes parent preflight evidence must not be a symlink")
    try:
        raw = path.read_bytes()
    except OSError as error:
        raise ValueError("Kubernetes parent preflight evidence could not be read") from error
    if len(raw) > KUBERNETES_PREFLIGHT_MAX_BYTES:
        raise ValueError("Kubernetes parent preflight evidence exceeds the size limit")
    try:
        envelope = _strict_json_object(raw.decode("utf-8"))
    except UnicodeDecodeError as error:
        raise ValueError("Kubernetes parent preflight evidence is not UTF-8") from error
    expected_keys = {
        "schema_version",
        "run_id",
        "source_fingerprint",
        "image_digest",
        "preflight",
        "preflight_sha256",
        "token_sha256",
        "signature",
    }
    if set(envelope) != expected_keys:
        raise ValueError("Kubernetes parent preflight evidence fields are invalid")
    if envelope.get("schema_version") != KUBERNETES_PREFLIGHT_EVIDENCE_SCHEMA_VERSION:
        raise ValueError("Kubernetes parent preflight evidence schema is unsupported")
    run_id = os.getenv("TRPC_REAL_RUN_ID", "").strip()
    if _KUBERNETES_RUN_ID_RE.fullmatch(run_id) is None or envelope.get("run_id") != run_id:
        raise ValueError("Kubernetes parent preflight run ID does not match the Job")
    token = os.getenv(WORKER_TOKEN_ENV, "")
    if not token:
        raise ValueError("Kubernetes parent preflight worker token is missing")
    config = _kubernetes_configuration(args)
    expected_source = config.get("expected_source_fingerprint")
    expected_image = config.get("expected_image_digest")
    if not isinstance(expected_source, str) or not isinstance(expected_image, str):
        raise ValueError("Kubernetes parent preflight requires expected source and image")
    source_value = expected_source.lower()
    image_value = expected_image.lower()
    if (
        envelope.get("source_fingerprint") != source_value
        or envelope.get("image_digest") != image_value
    ):
        raise ValueError("Kubernetes parent preflight source or image binding mismatches")
    if envelope.get("token_sha256") != hashlib.sha256(token.encode("utf-8")).hexdigest():
        raise ValueError("Kubernetes parent preflight token binding mismatches")
    unsigned = {key: envelope[key] for key in expected_keys if key != "signature"}
    expected_signature = hmac.new(
        token.encode("utf-8"),
        _canonical_json(unsigned).encode("utf-8"),
        hashlib.sha256,
    ).hexdigest()
    signature = envelope.get("signature")
    if not isinstance(signature, str) or not hmac.compare_digest(signature, expected_signature):
        raise ValueError("Kubernetes parent preflight signature is invalid")
    preflight = envelope.get("preflight")
    if not isinstance(preflight, Mapping):
        raise ValueError("Kubernetes parent preflight payload is invalid")
    preflight_hash = hashlib.sha256(_canonical_json(preflight).encode("utf-8")).hexdigest()
    if envelope.get("preflight_sha256") != preflight_hash:
        raise ValueError("Kubernetes parent preflight payload hash mismatches")
    _validate_preflight_attestation(
        preflight,
        source_fingerprint=source_value,
        image_digest=image_value,
    )
    kubernetes = preflight.get("kubernetes")
    if (
        not isinstance(kubernetes, Mapping)
        or kubernetes.get("namespace") != config.get("namespace")
        or kubernetes.get("namespace_bound") is not True
    ):
        raise ValueError("Kubernetes parent preflight namespace binding is invalid")
    verified = dict(preflight)
    verified["kubernetes"] = {
        **dict(kubernetes),
        "preflight_evidence": {
            "status": "parent_attested",
            "schema_version": KUBERNETES_PREFLIGHT_EVIDENCE_SCHEMA_VERSION,
            "run_id": run_id,
            "preflight_sha256": preflight_hash,
            "source_fingerprint": source_value,
            "image_digest": image_value,
        },
    }
    return verified


def _preflight_for_execution(args: argparse.Namespace) -> dict[str, Any]:
    """Choose local kubectl preflight or the signed Job handoff."""

    if bool(getattr(args, "kubernetes_load_worker", False)):
        if not bool(getattr(args, "load_worker", False)):
            raise ValueError("Kubernetes load-worker handoff requires --load-worker")
        return _load_kubernetes_preflight_evidence(args)
    return _preflight(args)


def _kubernetes_kubectl(
    arguments: Sequence[str],
    configuration: Mapping[str, Any],
    *,
    timeout_seconds: float = 20.0,
) -> tuple[str, str]:
    """Run one bounded, read-only kubectl request and return status/stdout."""

    executable = shutil.which("kubectl")
    if executable is None:
        return "not_run", "kubectl is not installed"
    command = [executable]
    kubeconfig = configuration.get("kubeconfig")
    if isinstance(kubeconfig, str) and kubeconfig:
        command.extend(["--kubeconfig", kubeconfig])
    context = configuration.get("context")
    if not isinstance(context, str) or not context:
        return "not_run", "Kubernetes context is missing"
    command.extend(["--context", context])
    command.extend(str(argument) for argument in arguments)
    try:
        completed = subprocess.run(  # noqa: S603 - fixed kubectl executable and argv
            command,
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
            timeout=timeout_seconds,
        )
    except subprocess.TimeoutExpired:
        return "not_run", "kubectl request timed out"
    except OSError:
        return "not_run", "kubectl request could not start"
    if completed.returncode != 0:
        return "not_run", "kubectl request failed"
    return "pass", completed.stdout


def _kubernetes_json(
    arguments: Sequence[str],
    configuration: Mapping[str, Any],
) -> tuple[dict[str, Any] | None, str | None]:
    status, output = _kubernetes_kubectl(arguments, configuration)
    if status != "pass":
        return None, output
    try:
        payload = json.loads(output)
    except (TypeError, ValueError, json.JSONDecodeError):
        return None, "kubectl returned invalid JSON"
    if not isinstance(payload, dict):
        return None, "kubectl returned a non-object JSON payload"
    return payload, None


def _kubernetes_image_digest(value: Any) -> str | None:
    """Extract an immutable digest from the CRI ``imageID`` representation."""

    if not isinstance(value, str):
        return None
    match = _KUBERNETES_IMAGE_ID_RE.search(value.strip())
    if match is None:
        return None
    return match.group(1).lower()


def _kubernetes_quantity_bytes(value: Any) -> int | None:
    """Parse a bounded Kubernetes resource quantity into bytes."""

    if not isinstance(value, str):
        return None
    match = _KUBERNETES_QUANTITY_RE.fullmatch(value.strip())
    if match is None:
        return None
    try:
        numeric = Decimal(match.group("number"))
        factor = _KUBERNETES_QUANTITY_FACTORS[match.group("suffix") or ""]
        result = int(numeric * factor)
    except (InvalidOperation, KeyError, ValueError, OverflowError):
        return None
    if result <= 0 or result >= 2**60:
        return None
    return result


def _kubernetes_pod_records(
    configuration: Mapping[str, Any],
    *,
    role: str,
    selector: str,
) -> tuple[tuple[dict[str, Any], ...], str | None]:
    """Read ready role Pods and their immutable runtime identities."""

    namespace = configuration.get("namespace")
    if not isinstance(namespace, str):
        return (), "Kubernetes namespace is unavailable"
    payload, error = _kubernetes_json(
        [
            "get",
            "pods",
            "--namespace",
            namespace,
            "--selector",
            selector,
            "--output",
            "json",
        ],
        configuration,
    )
    if error is not None or payload is None:
        return (), error or "Kubernetes Pod inventory is unavailable"
    raw_items = payload.get("items")
    if not isinstance(raw_items, list):
        return (), "Kubernetes Pod inventory is invalid"
    records: list[dict[str, Any]] = []
    seen_pods: set[str] = set()
    container_name = role
    for raw_pod in raw_items:
        if not isinstance(raw_pod, Mapping):
            return (), "Kubernetes Pod inventory contains an invalid item"
        metadata = raw_pod.get("metadata")
        spec = raw_pod.get("spec")
        status = raw_pod.get("status")
        if not isinstance(metadata, Mapping) or not isinstance(spec, Mapping):
            return (), "Kubernetes Pod identity is incomplete"
        pod_name = metadata.get("name")
        pod_uid = metadata.get("uid")
        if (
            not isinstance(pod_name, str)
            or not pod_name
            or not isinstance(pod_uid, str)
            or not pod_uid
            or pod_name in seen_pods
        ):
            return (), "Kubernetes Pod identity is missing or duplicated"
        seen_pods.add(pod_name)
        if not isinstance(status, Mapping) or status.get("phase") != "Running":
            return (), f"Kubernetes {role} Pod is not running"
        raw_statuses = status.get("containerStatuses")
        raw_containers = spec.get("containers")
        if not isinstance(raw_statuses, list) or not isinstance(raw_containers, list):
            return (), f"Kubernetes {role} Pod container status is incomplete"
        container_status = next(
            (
                item
                for item in raw_statuses
                if isinstance(item, Mapping) and item.get("name") == container_name
            ),
            None,
        )
        container_spec = next(
            (
                item
                for item in raw_containers
                if isinstance(item, Mapping) and item.get("name") == container_name
            ),
            None,
        )
        if not isinstance(container_status, Mapping) or not isinstance(container_spec, Mapping):
            return (), f"Kubernetes {role} Pod container is missing"
        if container_status.get("ready") is not True:
            return (), f"Kubernetes {role} Pod container is not ready"
        container_state = container_status.get("state")
        if not isinstance(container_state, Mapping) or not isinstance(
            container_state.get("running"), Mapping
        ):
            return (), f"Kubernetes {role} Pod container is not running"
        image_digest = _kubernetes_image_digest(container_status.get("imageID"))
        container_id = container_status.get("containerID")
        if not isinstance(container_id, str) or not container_id.strip():
            return (), f"Kubernetes {role} Pod container ID is missing"
        if image_digest is None:
            return (), f"Kubernetes {role} Pod imageID is not an immutable digest"
        resources = container_spec.get("resources")
        limits = resources.get("limits") if isinstance(resources, Mapping) else None
        memory_limit = (
            _kubernetes_quantity_bytes(limits.get("memory"))
            if isinstance(limits, Mapping)
            else None
        )
        labels = metadata.get("labels")
        source_value = (
            labels.get(IMAGE_SOURCE_FINGERPRINT_LABEL) if isinstance(labels, Mapping) else None
        )
        if not isinstance(source_value, str):
            source_value = None
        source_value = source_value.lower() if source_value else None
        node_name = spec.get("nodeName")
        if not isinstance(node_name, str) or not node_name:
            return (), f"Kubernetes {role} Pod node identity is missing"
        records.append(
            {
                "role": role,
                "pod_name": pod_name,
                "pod_uid": pod_uid,
                "container_name": container_name,
                "container_id": container_id,
                "image_id": image_digest,
                "image_digest": image_digest,
                "source_fingerprint": source_value,
                "node_name": node_name,
                "process_count": 1,
                "memory_limit_bytes": memory_limit,
                "ready": True,
            }
        )
    return tuple(records), None


def _kubernetes_worker_concurrency(
    configuration: Mapping[str, Any],
) -> tuple[int | None, str | None]:
    """Read the locked worker concurrency from the service ConfigMap."""

    namespace = configuration.get("namespace")
    if not isinstance(namespace, str):
        return None, "Kubernetes namespace is unavailable for worker ConfigMap lookup"
    payload, error = _kubernetes_json(
        [
            "get",
            f"configmap/{KUBERNETES_SERVICE_CONFIGMAP}",
            "--namespace",
            namespace,
            "--output",
            "json",
        ],
        configuration,
    )
    if error is not None or payload is None:
        return None, error or "Kubernetes worker concurrency ConfigMap is unavailable"
    data = payload.get("data")
    if not isinstance(data, Mapping):
        return None, "Kubernetes worker concurrency ConfigMap data is missing"
    raw_value = data.get(KUBERNETES_WORKER_CONCURRENCY_KEY)
    observed: int | None = None
    if isinstance(raw_value, str):
        try:
            observed = int(raw_value.strip(), 10)
        except ValueError:
            pass
    if raw_value != str(PRODUCTION_WORKER_CONCURRENCY):
        return observed, (
            "Kubernetes TRPC_SERVICE_WORKER_CONCURRENCY must equal exactly "
            f"{PRODUCTION_WORKER_CONCURRENCY}"
        )
    return PRODUCTION_WORKER_CONCURRENCY, None


def _kubernetes_image_attestation(
    workers: Sequence[Mapping[str, Any]],
    *,
    expected_source: str | None,
    expected_image: str | None,
    role: str = "worker",
) -> dict[str, Any]:
    """Require one immutable role image and an explicit source binding."""

    if not workers:
        return {"status": "not_run", "reason": f"no Kubernetes {role} Pods were available"}
    image_ids: set[str] = set()
    source_values: set[str] = set()
    for worker in workers:
        image_id = _kubernetes_image_digest(worker.get("image_id"))
        if image_id is None:
            return {"status": "not_run", "reason": f"Kubernetes {role} imageID is invalid"}
        image_ids.add(image_id)
        source_value = worker.get("source_fingerprint")
        if isinstance(source_value, str) and _KUBERNETES_FINGERPRINT_RE.fullmatch(source_value):
            source_values.add(source_value)
        elif source_value not in (None, ""):
            return {
                "status": "not_run",
                "reason": f"Kubernetes {role} source fingerprint is invalid",
            }
    if len(image_ids) != 1:
        return {
            "status": "not_run",
            "reason": f"Kubernetes {role} Pods use mixed immutable image digests",
            "image_count": len(image_ids),
        }
    image_id = next(iter(image_ids))
    if expected_image is not None and image_id != expected_image.lower():
        return {
            "status": "not_run",
            "reason": f"Kubernetes {role} image digest does not match candidate",
        }
    if expected_source is None:
        if len(source_values) != 1:
            return {
                "status": "not_run",
                "reason": f"Kubernetes {role} source fingerprint binding is unavailable",
            }
        expected_source = next(iter(source_values))
        binding_method = "pod_label"
    else:
        if source_values and source_values != {expected_source}:
            return {
                "status": "not_run",
                "reason": f"Kubernetes {role} source fingerprint label is stale or mixed",
            }
        binding_method = "configured_candidate"
    return {
        "status": "pass",
        "worker_count": len(workers),
        "independent_process_count": len(workers),
        "image_count": 1,
        "image_id": image_id,
        "source_fingerprint": expected_source,
        "source_fingerprint_matches": True,
        "binding_method": binding_method,
    }


def _kubernetes_metrics_memory_observation(
    participating: Mapping[str, Sequence[Mapping[str, Any]]],
    metrics_payload: Mapping[str, Any],
    *,
    configured_limit_bytes: int | None = None,
) -> dict[str, Any]:
    """Convert PodMetrics API samples into complete role-bound evidence."""

    raw_items = metrics_payload.get("items")
    if not isinstance(raw_items, list):
        return {
            "status": "not_run",
            "reason": "Kubernetes metrics API returned no Pod metrics list",
            "required_roles": list(_SERVICE_ROLES),
            "coverage_complete": False,
        }
    metrics_by_pod: dict[str, Mapping[str, Any]] = {}
    duplicate_metrics = False
    for raw_item in raw_items:
        if not isinstance(raw_item, Mapping):
            continue
        metadata = raw_item.get("metadata")
        name = metadata.get("name") if isinstance(metadata, Mapping) else None
        if isinstance(name, str) and name:
            if name in metrics_by_pod:
                duplicate_metrics = True
            else:
                metrics_by_pod[name] = raw_item
    if duplicate_metrics:
        return {
            "status": "not_run",
            "reason": "Kubernetes metrics API returned duplicate Pod identities",
            "required_roles": list(_SERVICE_ROLES),
            "coverage_complete": False,
        }
    records: list[dict[str, Any]] = []
    role_observations: dict[str, Any] = {}
    all_observed = True
    sample_windows: list[float] = []
    sample_timestamps: set[str] = set()
    for role in _SERVICE_ROLES:
        identities = participating.get(role, ())
        role_records: list[dict[str, Any]] = []
        for identity in identities:
            pod_name = identity.get("pod_name")
            container_name = identity.get("container_name")
            pod_metrics = metrics_by_pod.get(pod_name) if isinstance(pod_name, str) else None
            raw_containers = pod_metrics.get("containers") if pod_metrics else None
            metric_container = next(
                (
                    item
                    for item in raw_containers or ()
                    if isinstance(item, Mapping) and item.get("name") == container_name
                ),
                None,
            )
            usage = metric_container.get("usage") if isinstance(metric_container, Mapping) else None
            memory_bytes = (
                _kubernetes_quantity_bytes(usage.get("memory"))
                if isinstance(usage, Mapping)
                else None
            )
            if memory_bytes is None:
                all_observed = False
            window = pod_metrics.get("window") if isinstance(pod_metrics, Mapping) else None
            window_seconds = (
                _kubernetes_duration_seconds(window) if isinstance(window, str) else None
            )
            if window_seconds is None:
                all_observed = False
            else:
                sample_windows.append(window_seconds)
            timestamp = pod_metrics.get("timestamp") if isinstance(pod_metrics, Mapping) else None
            if isinstance(timestamp, str) and timestamp:
                sample_timestamps.add(timestamp)
            else:
                all_observed = False
            record = {
                "role": role,
                "pod_name": pod_name,
                "pod_uid": identity.get("pod_uid"),
                "container_name": container_name,
                "container_id": identity.get("container_id"),
                "memory_bytes": memory_bytes,
                "sampled_memory_bytes": memory_bytes,
                "memory_limit_bytes": identity.get("memory_limit_bytes"),
                "sampling_source": "kubernetes_metrics_api",
                "metrics_timestamp": timestamp,
                "metrics_window": window,
            }
            role_records.append(record)
            records.append(record)
        if not identities or len(role_records) != len(identities):
            all_observed = False
        role_observations[role] = {
            "identity_count": len(identities),
            "observed_count": len(role_records)
            if all_observed
            else sum(1 for item in role_records if isinstance(item.get("memory_bytes"), int)),
            "observations": role_records,
        }
    observed_count = sum(1 for item in records if isinstance(item.get("memory_bytes"), int))
    limits = [item.get("memory_limit_bytes") for item in records]
    threshold: int | None
    if configured_limit_bytes is not None:
        threshold = configured_limit_bytes
    elif all(isinstance(value, int) and value > 0 for value in limits):
        threshold = sum(cast(int, value) for value in limits)
    else:
        threshold = None
    sampled_bytes = sum(
        cast(int, item["memory_bytes"])
        for item in records
        if isinstance(item.get("memory_bytes"), int)
    )
    within_limit = threshold is not None and sampled_bytes <= threshold
    status = "pass" if all_observed and within_limit else "not_run"
    if all_observed and threshold is not None and not within_limit:
        status = "fail"
    reason = None
    if not all_observed:
        reason = "Kubernetes metrics API lacks memory coverage for every role Pod"
    elif threshold is None:
        reason = "Kubernetes memory safety threshold is unavailable"
    elif not within_limit:
        reason = "Kubernetes sampled memory exceeds the safety threshold"
    return {
        "status": status,
        "sampling_method": "kubernetes_metrics_api",
        "metrics_api": KUBERNETES_METRICS_API,
        "sample_count": 1,
        "sampling_interval_seconds": max(sample_windows or [MEMORY_SAMPLE_INTERVAL_SECONDS]),
        "sample_timestamps": sorted(sample_timestamps),
        "required_roles": list(_SERVICE_ROLES),
        "role_observations": role_observations,
        "coverage_complete": all_observed,
        "observed_identity_count": observed_count,
        "sampled_memory_bytes": sampled_bytes if sampled_bytes > 0 else None,
        "peak_bytes": sampled_bytes if sampled_bytes > 0 else None,
        "safety_threshold_bytes": threshold,
        "threshold_source": (
            "configured" if configured_limit_bytes is not None else "pod_resource_limits"
        ),
        "within_safety_threshold": within_limit,
        "observed_at": datetime.now(UTC).isoformat().replace("+00:00", "Z"),
        **({"reason": reason} if reason else {}),
    }


def _kubernetes_duration_seconds(value: str) -> float | None:
    match = re.fullmatch(r"(?P<number>\d+(?:\.\d+)?)(?P<unit>s|m|h)$", value.strip())
    if match is None:
        return None
    try:
        number = float(match.group("number"))
    except ValueError:
        return None
    factor = {"s": 1.0, "m": 60.0, "h": 3600.0}[match.group("unit")]
    result = number * factor
    return result if math.isfinite(result) and result > 0 else None


def _kubernetes_preflight(
    args: argparse.Namespace,
    *,
    min_workers: int,
) -> dict[str, Any]:
    """Collect all Kubernetes evidence before a live load can start."""

    try:
        configuration = _kubernetes_configuration(args)
    except ValueError as error:
        return {"status": "not_run", "reason": str(error)}
    worker_concurrency, concurrency_error = _kubernetes_worker_concurrency(configuration)
    if concurrency_error is not None:
        return {
            "status": "not_run",
            "reason": concurrency_error,
            "worker_concurrency": worker_concurrency,
            "kubernetes": configuration,
        }
    workers, worker_error = _kubernetes_pod_records(
        configuration,
        role="worker",
        selector=KUBERNETES_WORKER_SELECTOR,
    )
    if worker_error is not None:
        return {"status": "not_run", "reason": worker_error, "kubernetes": configuration}
    outbox, outbox_error = _kubernetes_pod_records(
        configuration,
        role="outbox-dispatcher",
        selector=KUBERNETES_OUTBOX_SELECTOR,
    )
    if outbox_error is not None:
        return {"status": "not_run", "reason": outbox_error, "kubernetes": configuration}
    if len(workers) != PRODUCTION_MIN_WORKERS or len(workers) < min_workers:
        return {
            "status": "not_run",
            "reason": (
                "Kubernetes formal performance preflight requires exactly "
                f"{PRODUCTION_MIN_WORKERS} ready worker Pods, found {len(workers)}"
            ),
            "worker_processes": workers,
            "worker_count": len(workers),
            "worker_concurrency": worker_concurrency,
            "kubernetes": configuration,
        }
    if not outbox:
        return {
            "status": "not_run",
            "reason": "at least one ready Kubernetes outbox-dispatcher Pod is required",
            "worker_processes": workers,
            "kubernetes": configuration,
        }
    configured_source = configuration.get("expected_source_fingerprint")
    expected_image = cast(str | None, configuration.get("expected_image_digest"))
    current_source = _source_fingerprint()
    candidate_source = current_source.get("value")
    if configured_source is not None:
        if not isinstance(candidate_source, str) or candidate_source != configured_source:
            return {
                "status": "not_run",
                "reason": "configured Kubernetes source fingerprint does not match checkout",
                "worker_processes": workers,
                "kubernetes": configuration,
            }
        expected_source = configured_source
    elif (
        expected_image is not None
        and isinstance(candidate_source, str)
        and _KUBERNETES_FINGERPRINT_RE.fullmatch(candidate_source)
    ):
        # An explicitly bound candidate image may use the current checkout
        # source as its source side of the release binding.  Without an
        # expected image, require a source label from every Pod instead of
        # guessing that an arbitrary digest belongs to this checkout.
        expected_source = candidate_source
    else:
        expected_source = None
    attestation = _kubernetes_image_attestation(
        workers,
        expected_source=expected_source,
        expected_image=expected_image,
    )
    if attestation.get("status") != "pass":
        return {
            "status": "not_run",
            "reason": str(attestation.get("reason", "Kubernetes image attestation failed")),
            "worker_processes": workers,
            "kubernetes": configuration,
            "worker_image_attestation": attestation,
        }
    outbox_attestation = _kubernetes_image_attestation(
        outbox,
        expected_source=expected_source,
        expected_image=expected_image,
        role="outbox-dispatcher",
    )
    if outbox_attestation.get("status") != "pass":
        return {
            "status": "not_run",
            "reason": str(
                outbox_attestation.get("reason", "Kubernetes outbox image attestation failed")
            ),
            "worker_processes": workers,
            "kubernetes": configuration,
            "worker_image_attestation": attestation,
            "service_image_attestation": {
                "worker": attestation,
                "outbox-dispatcher": outbox_attestation,
            },
        }
    attested_source = attestation.get("source_fingerprint")
    if not isinstance(candidate_source, str) or attested_source != candidate_source:
        return {
            "status": "not_run",
            "reason": "Kubernetes source fingerprint is not bound to this checkout",
            "worker_processes": workers,
            "kubernetes": configuration,
            "worker_image_attestation": attestation,
            "service_image_attestation": {
                "worker": attestation,
                "outbox-dispatcher": outbox_attestation,
            },
        }
    namespace = cast(str, configuration["namespace"])
    metrics_payload, metrics_error = _kubernetes_json(
        [
            "get",
            "--raw",
            f"/apis/{KUBERNETES_METRICS_API}/namespaces/{namespace}/pods",
        ],
        configuration,
    )
    if metrics_error is not None or metrics_payload is None:
        return {
            "status": "not_run",
            "reason": metrics_error or "Kubernetes metrics API is unavailable",
            "worker_processes": workers,
            "kubernetes": configuration,
            "worker_image_attestation": attestation,
            "service_image_attestation": {
                "worker": attestation,
                "outbox-dispatcher": outbox_attestation,
            },
        }
    participating = {
        "worker": workers,
        "outbox-dispatcher": outbox,
    }
    memory_observation = _kubernetes_metrics_memory_observation(
        participating,
        metrics_payload,
        configured_limit_bytes=cast(int | None, configuration.get("memory_limit_bytes")),
    )
    if memory_observation.get("status") != "pass":
        return {
            "status": "not_run",
            "reason": str(
                memory_observation.get("reason", "Kubernetes memory evidence is unavailable")
            ),
            "worker_processes": workers,
            "participating_processes": participating,
            "kubernetes": configuration,
            "worker_image_attestation": attestation,
            "service_image_attestation": {
                "worker": attestation,
                "outbox-dispatcher": outbox_attestation,
            },
            "memory_observation": memory_observation,
        }
    return {
        "status": "pass",
        "worker_processes": workers,
        "worker_count": len(workers),
        "worker_concurrency": worker_concurrency,
        "participating_processes": participating,
        "kubernetes": {
            **configuration,
            "metrics_api": KUBERNETES_METRICS_API,
            "namespace_bound": True,
        },
        "worker_image_attestation": attestation,
        "service_image_attestation": {
            "worker": attestation,
            "outbox-dispatcher": outbox_attestation,
        },
        "memory_observation": memory_observation,
    }


def _worker_processes() -> tuple[dict[str, int | str], ...]:
    """Find independent worker identities without requiring psutil or Docker."""

    if _kubernetes_mode():
        try:
            configuration = _kubernetes_configuration()
        except ValueError:
            return ()
        workers, error = _kubernetes_pod_records(
            configuration,
            role="worker",
            selector=KUBERNETES_WORKER_SELECTOR,
        )
        if error is not None:
            return ()
        return tuple(cast(dict[str, int | str], worker) for worker in workers)

    real_compose_project = os.getenv("TRPC_REAL_COMPOSE_PROJECT", "").strip()
    performance_compose_project = os.getenv("TRPC_PERF_COMPOSE_PROJECT", "").strip()
    if (
        real_compose_project
        and performance_compose_project
        and real_compose_project != performance_compose_project
    ):
        return ()

    explicit = os.getenv("TRPC_REAL_WORKER_PIDS", "").strip()
    if explicit:
        explicit_processes: list[dict[str, int | str]] = []
        seen_pids: set[int] = set()
        for value in explicit.split(","):
            try:
                pid = int(value.strip())
            except ValueError:
                continue
            if pid > 1 and pid not in seen_pids and _pid_alive(pid):
                seen_pids.add(pid)
                explicit_processes.append({"pid": pid})
        return tuple(explicit_processes)

    compose_project = real_compose_project or performance_compose_project
    if compose_project:
        return _compose_worker_processes(compose_project)

    ps = shutil.which("ps")
    if ps is None:
        return ()
    try:
        completed = subprocess.run(  # noqa: S603 - fixed process inspection command
            [ps, "-eo", "pid=,args="],
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.TimeoutExpired):
        return ()
    if completed.returncode != 0:
        return ()
    processes: list[dict[str, int | str]] = []
    process_seen_pids: set[int] = set()
    for line in completed.stdout.splitlines():
        match = re.match(r"\s*(\d+)\s+(.*)$", line)
        if match is None or not _WORKER_RE.search(match.group(2)):
            continue
        pid = int(match.group(1))
        if pid > 1 and pid not in process_seen_pids:
            process_seen_pids.add(pid)
            processes.append({"pid": pid})
    return tuple(processes)


_SERVICE_ROLES = MEMORY_REQUIRED_ROLES


def _compose_service_processes(project: str, role: str) -> tuple[dict[str, int | str], ...]:
    """Discover one compose service's process identity without mutating Docker.

    The performance run is allowed to inspect an already-running deployment,
    but it must not infer service memory from the load-generator process.  The
    container init PID is useful because its cgroup contains the whole service
    container; the cgroup sampler below reports the aggregate container peak.
    """

    docker = shutil.which("docker")
    if docker is None or role not in _SERVICE_ROLES:
        return ()
    try:
        listed = subprocess.run(  # noqa: S603 - fixed Docker executable/labels
            [
                docker,
                "ps",
                "--filter",
                f"label=com.docker.compose.project={project}",
                "--filter",
                f"label=com.docker.compose.service={role}",
                "--format",
                "{{.ID}}",
            ],
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.TimeoutExpired):
        return ()
    if listed.returncode != 0:
        return ()
    identities: list[dict[str, int | str]] = []
    seen: set[str] = set()
    for container_id in (line.strip() for line in listed.stdout.splitlines()):
        if not container_id or container_id in seen:
            continue
        seen.add(container_id)
        try:
            inspected = subprocess.run(  # noqa: S603 - ID came from Docker itself
                [docker, "inspect", "--format", "{{json .}}", container_id],
                cwd=ROOT,
                check=False,
                capture_output=True,
                text=True,
                timeout=10,
            )
        except (OSError, subprocess.TimeoutExpired):
            continue
        if inspected.returncode != 0:
            continue
        try:
            details = json.loads(inspected.stdout)
        except (TypeError, ValueError):
            continue
        if not isinstance(details, Mapping):
            continue
        state = details.get("State")
        config = details.get("Config")
        if not isinstance(state, Mapping) or not isinstance(config, Mapping):
            continue
        if state.get("Running") is not True:
            continue
        labels = config.get("Labels") or {}
        if not isinstance(labels, Mapping):
            continue
        try:
            pid = int(state.get("Pid", 0))
        except (TypeError, ValueError):
            continue
        inspected_id = details.get("Id")
        image_id = details.get("Image")
        if pid <= 1 or not isinstance(inspected_id, str) or not inspected_id:
            continue
        identity: dict[str, int | str] = {
            "role": role,
            "container_id": inspected_id,
            "pid": pid,
        }
        if isinstance(image_id, str) and image_id:
            identity["image_id"] = image_id
        source_value = labels.get(IMAGE_SOURCE_FINGERPRINT_LABEL)
        if isinstance(source_value, str) and source_value:
            identity["source_fingerprint"] = source_value
        identities.append(identity)
    return tuple(identities)


def _local_service_processes() -> dict[str, tuple[dict[str, int | str], ...]]:
    """Discover service roles from a local process table, read-only."""

    result: dict[str, list[dict[str, int | str]]] = {role: [] for role in _SERVICE_ROLES}
    ps = shutil.which("ps")
    if ps is None:
        return {role: tuple(items) for role, items in result.items()}
    try:
        completed = subprocess.run(  # noqa: S603 - fixed process inspection command
            [ps, "-eo", "pid=,args="],
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.TimeoutExpired):
        return {role: tuple(items) for role, items in result.items()}
    if completed.returncode != 0:
        return {role: tuple(items) for role, items in result.items()}
    seen: set[tuple[str, int]] = set()
    role_pattern = re.compile(
        r"(?:trpc-service|trpc_service).*serve\s+--role\s+"
        r"(worker|outbox-dispatcher|channel-dispatcher|post-turn-projector)(?:\s|$)"
    )
    for line in completed.stdout.splitlines():
        match = re.match(r"\s*(\d+)\s+(.*)$", line)
        if match is None:
            continue
        try:
            pid = int(match.group(1))
        except ValueError:
            continue
        role_match = role_pattern.search(match.group(2))
        if role_match is None or pid <= 1:
            continue
        role = role_match.group(1)
        key = (role, pid)
        if key in seen:
            continue
        seen.add(key)
        result[role].append({"role": role, "pid": pid})
    return {role: tuple(items) for role, items in result.items()}


def _participating_processes(
    workers: Sequence[Mapping[str, Any]],
) -> dict[str, tuple[dict[str, int | str], ...]]:
    """Return the exact process/container set whose memory is production evidence."""

    result: dict[str, list[dict[str, int | str]]] = {role: [] for role in _SERVICE_ROLES}
    for worker in workers:
        item = dict(worker)
        item["role"] = "worker"
        result["worker"].append(cast(dict[str, int | str], item))
    real_project = os.getenv("TRPC_REAL_COMPOSE_PROJECT", "").strip()
    perf_project = os.getenv("TRPC_PERF_COMPOSE_PROJECT", "").strip()
    project = real_project or perf_project
    if project:
        for role in _SERVICE_ROLES[1:]:
            result[role].extend(_compose_service_processes(project, role))
    else:
        local = _local_service_processes()
        for role in _SERVICE_ROLES[1:]:
            result[role].extend(local[role])
    return {role: tuple(items) for role, items in result.items()}


def _read_numeric_file(path: Path) -> int | None:
    try:
        raw = path.read_text(encoding="ascii").strip()
    except (OSError, UnicodeError):
        return None
    if not raw or raw == "max":
        return None
    try:
        value = int(raw)
    except ValueError:
        return None
    return value if 0 <= value < 2**60 else None


def _proc_cgroup_memory_paths(pid: int) -> tuple[Path, ...]:
    """Resolve memory cgroup directories for a process without shelling out."""

    try:
        lines = Path(f"/proc/{pid}/cgroup").read_text(encoding="ascii").splitlines()
    except (OSError, UnicodeError):
        return ()
    paths: list[Path] = []
    for line in lines:
        parts = line.split(":", 2)
        if len(parts) != 3:
            continue
        hierarchy, controllers, relative = parts
        if hierarchy != "0" and "memory" not in controllers.split(","):
            continue
        relative_path = relative.lstrip("/")
        roots = [Path("/sys/fs/cgroup")]
        if hierarchy != "0":
            roots.append(Path("/sys/fs/cgroup/memory"))
        for root in roots:
            candidate = root / relative_path
            if candidate not in paths:
                paths.append(candidate)
    return tuple(paths)


def _process_memory_snapshot(pid: int) -> dict[str, int | str | None]:
    """Read RSS high-water and cgroup peak values for one process."""

    snapshot: dict[str, int | str | None] = {
        "pid": pid,
        "rss_bytes": None,
        "rss_peak_bytes": None,
        "cgroup_current_bytes": None,
        "cgroup_peak_bytes": None,
        "cgroup_limit_bytes": None,
        "cgroup_key": None,
    }
    try:
        lines = Path(f"/proc/{pid}/status").read_text(encoding="ascii").splitlines()
    except (OSError, UnicodeError):
        lines = []
    values: dict[str, int] = {}
    for line in lines:
        name, separator, raw = line.partition(":")
        if separator and name in {"VmRSS", "VmHWM"}:
            pieces = raw.strip().split()
            if pieces:
                try:
                    multiplier = 1024 if len(pieces) == 1 or pieces[1] == "kB" else 1
                    values[name] = int(pieces[0]) * multiplier
                except ValueError:
                    pass
    snapshot["rss_bytes"] = values.get("VmRSS")
    snapshot["rss_peak_bytes"] = values.get("VmHWM")
    for cgroup in _proc_cgroup_memory_paths(pid):
        current = _read_numeric_file(cgroup / "memory.current")
        peak = _read_numeric_file(cgroup / "memory.peak")
        limit = _read_numeric_file(cgroup / "memory.max")
        if current is None and peak is None and limit is None:
            current = _read_numeric_file(cgroup / "memory.usage_in_bytes")
            peak = _read_numeric_file(cgroup / "memory.max_usage_in_bytes")
            limit = _read_numeric_file(cgroup / "memory.limit_in_bytes")
        if current is not None or peak is not None or limit is not None:
            snapshot.update(
                {
                    "cgroup_current_bytes": current,
                    "cgroup_peak_bytes": peak,
                    "cgroup_limit_bytes": limit,
                    "cgroup_key": str(cgroup),
                }
            )
            break
    return snapshot


def _container_memory_snapshot(container_id: str) -> dict[str, int | str | None]:
    """Read kernel peak counters from inside a Docker container.

    Docker Desktop exposes Linux container PIDs that are not addressable via
    the Windows host's ``/proc``.  The fallback is still kernel evidence: it
    reads PID 1's VmHWM and the container's memory cgroup files without
    changing the container or relying on ``docker stats`` estimates.
    """

    snapshot: dict[str, int | str | None] = {
        "container_id": container_id,
        "rss_bytes": None,
        "rss_peak_bytes": None,
        "cgroup_current_bytes": None,
        "cgroup_peak_bytes": None,
        "cgroup_limit_bytes": None,
        "cgroup_key": None,
        "sampling_source": "container_procfs",
    }
    if re.fullmatch(r"[0-9a-f]{12,64}", container_id) is None:
        return snapshot
    docker = shutil.which("docker")
    if docker is None:
        return snapshot
    probe = (
        'awk \'/^(VmRSS|VmHWM):/ {gsub(":", "", $1); '
        'print $1 "=" $2}\' /proc/1/status 2>/dev/null; '
        "for f in memory.current memory.peak memory.max memory.usage_in_bytes "
        "memory.max_usage_in_bytes memory.limit_in_bytes; do "
        "for root in /sys/fs/cgroup /sys/fs/cgroup/memory; do "
        'p="$root/$f"; if [ -r "$p" ]; then printf \'%s=\' "$f"; '
        'cat "$p"; break; fi; done; done'
    )
    try:
        completed = subprocess.run(  # noqa: S603 - fixed read-only Docker probe
            [docker, "exec", container_id, "sh", "-c", probe],
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.SubprocessError):
        return snapshot
    if completed.returncode != 0:
        return snapshot
    values: dict[str, int] = {}
    for line in completed.stdout.splitlines():
        name, separator, raw = line.partition("=")
        if not separator or raw.strip() == "max":
            continue
        try:
            value = int(raw.strip().split()[0])
        except (IndexError, ValueError):
            continue
        if name in {"VmRSS", "VmHWM"}:
            value *= 1024
        if 0 <= value < 2**60:
            values[name] = value
    snapshot.update(
        {
            "rss_bytes": values.get("VmRSS"),
            "rss_peak_bytes": values.get("VmHWM"),
            "cgroup_current_bytes": values.get("memory.current")
            or values.get("memory.usage_in_bytes"),
            "cgroup_peak_bytes": values.get("memory.peak")
            or values.get("memory.max_usage_in_bytes"),
            "cgroup_limit_bytes": values.get("memory.max") or values.get("memory.limit_in_bytes"),
            "cgroup_key": f"docker:{container_id}",
        }
    )
    return snapshot


def _memory_observation(
    participating: Mapping[str, Sequence[Mapping[str, Any]]],
    *,
    resources: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Build bounded, production-safe memory evidence from real identities.

    ``VmHWM`` is the kernel-maintained RSS high-water mark.  Where a process
    belongs to a memory cgroup, the cgroup peak is preferred and deduplicated
    by cgroup path so multiple roles in one cgroup cannot inflate the total.
    Missing observations are never replaced with estimates; the result is
    explicitly ``not_run`` and the release gate must refuse promotion.
    """

    started_at = datetime.now(UTC).isoformat().replace("+00:00", "Z")
    total = sum(len(participating.get(role, ())) for role in _SERVICE_ROLES)
    if total == 0 or total > MEMORY_MAX_IDENTITIES:
        return {
            "status": "not_run",
            "reason": "participating memory identities are missing or exceed the safety bound",
            "required_roles": list(_SERVICE_ROLES),
            "observed_at": started_at,
            "coverage_complete": False,
        }
    role_observations: dict[str, Any] = {}
    all_observed = True
    records: list[dict[str, Any]] = []
    for role in _SERVICE_ROLES:
        identities = participating.get(role, ())
        role_records: list[dict[str, Any]] = []
        for identity in identities:
            pid = identity.get("pid")
            if isinstance(pid, bool) or not isinstance(pid, int) or pid <= 1:
                all_observed = False
                continue
            sample = _process_memory_snapshot(pid)
            container_id = identity.get("container_id")
            if (
                not isinstance(sample.get("rss_peak_bytes"), int)
                and not isinstance(sample.get("cgroup_peak_bytes"), int)
                and isinstance(container_id, str)
            ):
                sample = _container_memory_snapshot(container_id)
            rss_peak = sample.get("rss_peak_bytes")
            cgroup_peak = sample.get("cgroup_peak_bytes")
            if not isinstance(rss_peak, int) and not isinstance(cgroup_peak, int):
                all_observed = False
            record = {
                "role": role,
                "pid": pid,
                "container_id": identity.get("container_id"),
                "rss_peak_bytes": rss_peak,
                "cgroup_peak_bytes": cgroup_peak,
                "cgroup_current_bytes": sample.get("cgroup_current_bytes"),
                "cgroup_limit_bytes": sample.get("cgroup_limit_bytes"),
                "cgroup_key": sample.get("cgroup_key"),
                "sampling_source": sample.get("sampling_source", "host_procfs"),
            }
            role_records.append(record)
            records.append(record)
        role_observations[role] = {
            "identity_count": len(identities),
            "observed_count": len(role_records),
            "observations": role_records,
        }
        if not identities or len(role_records) != len(identities):
            all_observed = False
    cgroup_records = [item for item in records if isinstance(item.get("cgroup_key"), str)]
    unique_cgroups: dict[str, dict[str, Any]] = {}
    for item in cgroup_records:
        key = cast(str, item["cgroup_key"])
        unique_cgroups[key] = item
    cgroup_peak = sum(
        int(item["cgroup_peak_bytes"])
        for item in unique_cgroups.values()
        if isinstance(item.get("cgroup_peak_bytes"), int)
    )
    rss_peak = sum(
        int(item["rss_peak_bytes"])
        for item in records
        if isinstance(item.get("rss_peak_bytes"), int)
    )
    cgroup_limit = sum(
        int(item["cgroup_limit_bytes"])
        for item in unique_cgroups.values()
        if isinstance(item.get("cgroup_limit_bytes"), int) and int(item["cgroup_limit_bytes"]) > 0
    )
    peak_bytes = cgroup_peak if cgroup_peak > 0 else rss_peak
    resource_limit = resources.get("available_memory_bytes") if resources else None
    threshold = cgroup_limit if cgroup_limit > 0 else resource_limit
    within_limit = isinstance(threshold, int) and threshold > 0 and peak_bytes <= threshold
    status = "pass" if all_observed and within_limit else ("fail" if all_observed else "not_run")
    reason = None
    if not all_observed:
        reason = "one or more participating service identities lack real RSS/cgroup peak evidence"
    elif not within_limit:
        reason = "observed memory peak exceeds the measured safety threshold"
    return {
        "status": status,
        "sampling_method": "kernel_peak_counters",
        "sample_count": 1,
        "sampling_interval_seconds": MEMORY_SAMPLE_INTERVAL_SECONDS,
        "required_roles": list(_SERVICE_ROLES),
        "role_observations": role_observations,
        "coverage_complete": all_observed,
        "observed_identity_count": len(records),
        "cgroup_identity_count": len(cgroup_records),
        "cgroup_scope_count": len(unique_cgroups),
        "peak_rss_bytes": rss_peak if rss_peak > 0 else None,
        "peak_cgroup_bytes": cgroup_peak if cgroup_peak > 0 else None,
        "peak_bytes": peak_bytes if peak_bytes > 0 else None,
        "safety_threshold_bytes": threshold,
        "threshold_source": "cgroup_limit" if cgroup_limit > 0 else "available_memory",
        "within_safety_threshold": within_limit,
        "observed_at": started_at,
        **({"reason": reason} if reason else {}),
    }


def _available_memory_bytes() -> int | None:
    """Return available memory without importing a process-management package."""

    if os.name == "nt":

        class MemoryStatus(ctypes.Structure):
            _fields_ = [
                ("length", ctypes.c_ulong),
                ("memory_load", ctypes.c_ulong),
                ("total_physical", ctypes.c_ulonglong),
                ("available_physical", ctypes.c_ulonglong),
                ("total_page_file", ctypes.c_ulonglong),
                ("available_page_file", ctypes.c_ulonglong),
                ("total_virtual", ctypes.c_ulonglong),
                ("available_virtual", ctypes.c_ulonglong),
                ("available_extended_virtual", ctypes.c_ulonglong),
            ]

        status = MemoryStatus()
        status.length = ctypes.sizeof(MemoryStatus)
        try:
            windll = getattr(ctypes, "windll", None)
            if windll is not None and windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(status)):
                return int(status.available_physical)
        except (AttributeError, OSError):
            return None
        return None

    meminfo = Path("/proc/meminfo")
    if not meminfo.exists():
        return None
    try:
        for line in meminfo.read_text(encoding="ascii").splitlines():
            name, _, raw_value = line.partition(":")
            if name.strip() == "MemAvailable":
                value, _, unit = raw_value.strip().partition(" ")
                multiplier = 1024 if unit.lower() == "kb" else 1
                return int(value) * multiplier
    except (OSError, ValueError):
        return None
    return None


def _cgroup_value(path: Path) -> int | None:
    """Read one Linux cgroup numeric value without trusting ``max``."""

    try:
        raw = path.read_text(encoding="ascii").strip()
    except (OSError, UnicodeError):
        return None
    if not raw or raw == "max":
        return None
    try:
        value = int(raw)
    except ValueError:
        return None
    # v1 uses an effectively-infinite sentinel on some hosts.  Treat it as
    # unlimited rather than accidentally making the preflight unusable.
    return value if 0 < value < 2**60 else None


def _cgroup_memory_limit_bytes() -> int | None:
    """Return the current cgroup memory limit when one is enforceable."""

    for path in (
        Path("/sys/fs/cgroup/memory.max"),
        Path("/sys/fs/cgroup/memory/memory.limit_in_bytes"),
    ):
        value = _cgroup_value(path)
        if value is not None:
            return value
    return None


def _cgroup_memory_current_bytes() -> int | None:
    """Return current cgroup memory usage, if the kernel exposes it."""

    for path in (
        Path("/sys/fs/cgroup/memory.current"),
        Path("/sys/fs/cgroup/memory/memory.usage_in_bytes"),
    ):
        value = _cgroup_value(path)
        if value is not None:
            return value
    return None


def _cgroup_cpu_quota_count() -> int | None:
    """Return the integer CPU capacity imposed by cgroup v2/v1."""

    try:
        raw = Path("/sys/fs/cgroup/cpu.max").read_text(encoding="ascii").split()
        if len(raw) >= 2 and raw[0] != "max":
            quota, period = int(raw[0]), int(raw[1])
            if quota > 0 and period > 0:
                return max(1, math.floor(quota / period))
    except (OSError, UnicodeError, ValueError):
        pass
    try:
        quota = int(Path("/sys/fs/cgroup/cpu/cpu.cfs_quota_us").read_text(encoding="ascii"))
        period = int(Path("/sys/fs/cgroup/cpu/cpu.cfs_period_us").read_text(encoding="ascii"))
        if quota > 0 and period > 0:
            return max(1, math.floor(quota / period))
    except (OSError, UnicodeError, ValueError):
        return None
    return None


def _resource_snapshot() -> dict[str, int | None]:
    host_cpu_count = int(os.cpu_count() or 0)
    cpu_quota_count = _cgroup_cpu_quota_count()
    cpu_count = (
        min(host_cpu_count, cpu_quota_count)
        if cpu_quota_count is not None and host_cpu_count
        else cpu_quota_count or host_cpu_count
    )
    host_available = _available_memory_bytes()
    memory_limit = _cgroup_memory_limit_bytes()
    memory_current = _cgroup_memory_current_bytes()
    cgroup_available = None
    if memory_limit is not None and memory_current is not None:
        cgroup_available = max(0, memory_limit - memory_current)
    available = host_available
    if memory_limit is not None and memory_current is None:
        # A known hard limit with an unreadable usage counter cannot be
        # converted into a safe free-memory estimate.  Do not fall back to
        # host-wide memory, which may greatly overstate the container budget.
        available = None
    elif cgroup_available is not None:
        available = cgroup_available if available is None else min(available, cgroup_available)
    return {
        "cpu_count": cpu_count,
        "host_cpu_count": host_cpu_count,
        "cpu_quota_count": cpu_quota_count,
        "available_memory_bytes": available,
        "host_available_memory_bytes": host_available,
        "cgroup_memory_limit_bytes": memory_limit,
        "cgroup_memory_current_bytes": memory_current,
        "cgroup_available_memory_bytes": cgroup_available,
    }


def _estimated_runtime_connections(*, min_workers: int, db_pool_size: int) -> int:
    """Estimate the fixed performance topology's simultaneous DB sessions."""

    return (
        GATEWAY_POOL_MAX_SIZE
        + (max(0, min_workers) * WORKER_POOL_MAX_SIZE)
        + OUTBOX_POOL_MAX_SIZE
        + RECOVERY_POOL_MAX_SIZE
        + max(0, db_pool_size)
        + PROBE_CONNECTION_HEADROOM
    )


def _required_memory_bytes(
    *,
    db_pool_size: int,
    max_inflight: int,
    burst_turns: int,
) -> int:
    """Calculate a bounded, conservative memory floor for the load process.

    The two-GiB base reserves room for the service and its databases.  The
    parameter increments are intentionally coarse upper-bound estimates; the
    final increment is capped so malformed or unusually large inputs cannot
    turn this calculation into an unbounded resource request.
    """

    increment = (
        max(0, db_pool_size) * MEMORY_PER_DB_POOL_CONNECTION_BYTES
        + max(0, max_inflight) * MEMORY_PER_INFLIGHT_REQUEST_BYTES
        + max(0, burst_turns) * MEMORY_PER_BURST_TURN_BYTES
    )
    return MIN_AVAILABLE_MEMORY_BYTES + min(
        increment,
        MAX_DYNAMIC_MEMORY_INCREMENT_BYTES,
    )


def _live_opt_in(args: argparse.Namespace, *, require_worker: bool = False) -> bool:
    """Require independent CLI, environment, and (for workers) capability opt-ins."""

    if not bool(getattr(args, "execute", False)):
        return False
    if not bool(getattr(args, "confirm_real_load", False)):
        return False
    if os.getenv(OPT_IN) != "1":
        return False
    if os.getenv(CONFIRM_REAL_LOAD_ENV) != CONFIRM_REAL_LOAD_VALUE:
        return False
    return not require_worker or bool(os.getenv(WORKER_TOKEN_ENV))


def _opt_in_reasons(args: argparse.Namespace, *, require_worker: bool = False) -> list[str]:
    reasons: list[str] = []
    if not bool(getattr(args, "execute", False)):
        reasons.append("--execute is required")
    if os.getenv(OPT_IN) != "1":
        reasons.append(f"{OPT_IN}=1 is required")
    if not bool(getattr(args, "confirm_real_load", False)):
        reasons.append("--confirm-real-load is required for the dedicated live-load command")
    if os.getenv(CONFIRM_REAL_LOAD_ENV) != CONFIRM_REAL_LOAD_VALUE:
        reasons.append(f"{CONFIRM_REAL_LOAD_ENV}={CONFIRM_REAL_LOAD_VALUE} is required")
    if require_worker and not os.getenv(WORKER_TOKEN_ENV):
        reasons.append("load worker capability token is missing")
    return reasons


def _hard_process_timeout(args: argparse.Namespace) -> float:
    configured = float(getattr(args, "timeout_seconds", DEFAULT_TIMEOUT_SECONDS))
    if not math.isfinite(configured) or configured <= 0:
        return 0.0
    return min(
        MAX_LOAD_PROCESS_TIMEOUT_SECONDS,
        max(30.0, (configured * 3.0) + 30.0),
    )


def _preflight(args: argparse.Namespace) -> dict[str, Any]:
    callbacks = int(args.callbacks)
    burst_turns = int(args.burst_turns)
    callback_rate = float(args.callback_rate)
    min_workers = int(args.min_workers)
    db_pool_size = int(args.db_pool_size)
    max_inflight = int(getattr(args, "max_inflight", DEFAULT_MAX_INFLIGHT))
    timeout_seconds = float(args.timeout_seconds)
    if callbacks < 1 or burst_turns < 1:
        return {"status": "fail", "reason": "callback and burst counts must be positive"}
    if callbacks > MAX_CALLBACKS:
        return {
            "status": "fail",
            "reason": f"callback count exceeds safety limit {MAX_CALLBACKS}",
        }
    if burst_turns > MAX_BURST_TURNS:
        return {
            "status": "fail",
            "reason": f"burst turn count exceeds safety limit {MAX_BURST_TURNS}",
        }
    if not math.isfinite(callback_rate) or callback_rate <= 0:
        return {"status": "fail", "reason": "callback rate must be finite and positive"}
    if callback_rate > MAX_CALLBACK_RATE:
        return {
            "status": "fail",
            "reason": f"callback rate exceeds safety limit {MAX_CALLBACK_RATE:g}",
        }
    if min_workers < 2:
        return {"status": "fail", "reason": "at least two independent workers are required"}
    if min_workers > MAX_MIN_WORKERS:
        return {
            "status": "fail",
            "reason": f"worker count exceeds safety limit {MAX_MIN_WORKERS}",
        }
    if db_pool_size < 2:
        return {"status": "fail", "reason": "database pool and timeout must be positive"}
    if db_pool_size > MAX_DB_POOL_SIZE:
        return {
            "status": "fail",
            "reason": f"database pool size exceeds safety limit {MAX_DB_POOL_SIZE}",
        }
    if max_inflight < 1 or max_inflight > MAX_INFLIGHT:
        return {
            "status": "fail",
            "reason": f"in-flight limit exceeds safety limit {MAX_INFLIGHT}",
        }
    if db_pool_size > max_inflight:
        return {
            "status": "fail",
            "reason": "database pool size must not exceed the in-flight limit",
        }
    if not math.isfinite(timeout_seconds) or timeout_seconds <= 0:
        return {
            "status": "fail",
            "reason": "timeout must be finite and positive",
        }
    if timeout_seconds > MAX_TIMEOUT_SECONDS:
        return {
            "status": "fail",
            "reason": f"timeout exceeds safety limit {MAX_TIMEOUT_SECONDS:g}s",
        }
    required_memory_bytes = _required_memory_bytes(
        db_pool_size=db_pool_size,
        max_inflight=max_inflight,
        burst_turns=burst_turns,
    )
    resources = _resource_snapshot()
    resources["required_memory_bytes"] = required_memory_bytes
    estimated_connections = _estimated_runtime_connections(
        min_workers=min_workers,
        db_pool_size=db_pool_size,
    )
    resources["estimated_runtime_connections"] = estimated_connections
    resources["max_estimated_runtime_connections"] = MAX_ESTIMATED_RUNTIME_CONNECTIONS
    if estimated_connections > MAX_ESTIMATED_RUNTIME_CONNECTIONS:
        return {
            "status": "not_run",
            "reason": (
                "estimated runtime PostgreSQL connections exceed the safety budget "
                f"of {MAX_ESTIMATED_RUNTIME_CONNECTIONS}"
            ),
            "resources": resources,
        }
    cpu_count = int(resources["cpu_count"] or 0)
    if cpu_count < min_workers:
        return {
            "status": "not_run",
            "reason": f"need at least {min_workers} CPUs, found {cpu_count}",
            "resources": resources,
        }
    available_memory = resources["available_memory_bytes"]
    if available_memory is None:
        return {
            "status": "not_run",
            "reason": "available memory could not be determined safely",
            "resources": resources,
        }
    if available_memory < required_memory_bytes:
        return {
            "status": "not_run",
            "reason": (
                "available memory is below the required performance safety threshold "
                f"of {required_memory_bytes} bytes"
            ),
            "resources": resources,
        }
    if _kubernetes_mode(args):
        kubernetes_preflight = _kubernetes_preflight(args, min_workers=min_workers)
        if kubernetes_preflight.get("status") != "pass":
            kubernetes_preflight.setdefault("resources", resources)
            return kubernetes_preflight
        workers_value = kubernetes_preflight.get("worker_processes")
        if not isinstance(workers_value, Sequence) or isinstance(
            workers_value, (str, bytes, bytearray)
        ):
            return {
                "status": "not_run",
                "reason": "Kubernetes preflight returned no worker identities",
                "resources": resources,
            }
        workers = tuple(
            cast(dict[str, int | str], item) for item in workers_value if isinstance(item, Mapping)
        )
        if len(workers) != len(workers_value):
            return {
                "status": "not_run",
                "reason": "Kubernetes preflight returned invalid worker identities",
                "resources": resources,
            }
        estimated_connections = _estimated_runtime_connections(
            min_workers=len(workers),
            db_pool_size=db_pool_size,
        )
        resources["estimated_runtime_connections"] = estimated_connections
        if estimated_connections > MAX_ESTIMATED_RUNTIME_CONNECTIONS:
            return {
                "status": "not_run",
                "reason": (
                    "discovered Kubernetes runtime PostgreSQL connections exceed the safety "
                    f"budget of {MAX_ESTIMATED_RUNTIME_CONNECTIONS}"
                ),
                "worker_processes": workers,
                "resources": resources,
            }
        participating_value = kubernetes_preflight.get("participating_processes")
        memory_value = kubernetes_preflight.get("memory_observation")
        attestation_value = kubernetes_preflight.get("worker_image_attestation")
        worker_count = kubernetes_preflight.get("worker_count")
        worker_concurrency = kubernetes_preflight.get("worker_concurrency")
        if (
            worker_count != PRODUCTION_MIN_WORKERS
            or worker_concurrency != PRODUCTION_WORKER_CONCURRENCY
        ):
            return {
                "status": "not_run",
                "reason": "Kubernetes preflight worker topology is not locked to 4x50",
                "worker_count": worker_count,
                "worker_concurrency": worker_concurrency,
                "resources": resources,
            }
        if not isinstance(participating_value, Mapping) or not isinstance(memory_value, Mapping):
            return {
                "status": "not_run",
                "reason": "Kubernetes preflight returned incomplete service evidence",
                "worker_processes": workers,
                "resources": resources,
            }
        source = _source_fingerprint()
        return {
            "status": "pass",
            "worker_processes": workers,
            "worker_count": worker_count,
            "worker_concurrency": worker_concurrency,
            "participating_processes": dict(participating_value),
            "memory_observation": dict(memory_value),
            "resources": resources,
            "source_fingerprint": source,
            "worker_image_attestation": (
                dict(attestation_value) if isinstance(attestation_value, Mapping) else {}
            ),
            "service_image_attestation": (
                dict(kubernetes_preflight["service_image_attestation"])
                if isinstance(kubernetes_preflight.get("service_image_attestation"), Mapping)
                else {}
            ),
            "kubernetes": kubernetes_preflight.get("kubernetes", {}),
        }

    workers = _worker_processes()
    if len(workers) < min_workers:
        return {
            "status": "not_run",
            "reason": f"need {min_workers} independent worker processes, found {len(workers)}",
            "worker_processes": workers,
            "resources": resources,
        }
    actual_estimated_connections = _estimated_runtime_connections(
        min_workers=len(workers),
        db_pool_size=db_pool_size,
    )
    resources["estimated_runtime_connections"] = actual_estimated_connections
    if actual_estimated_connections > MAX_ESTIMATED_RUNTIME_CONNECTIONS:
        return {
            "status": "not_run",
            "reason": (
                "discovered runtime PostgreSQL connections exceed the safety budget "
                f"of {MAX_ESTIMATED_RUNTIME_CONNECTIONS}"
            ),
            "worker_processes": workers,
            "resources": resources,
        }
    source = _source_fingerprint()
    image_attestation = _worker_image_attestation(workers, source)
    participating = _participating_processes(workers)
    memory_observation = _memory_observation(participating, resources=resources)
    return {
        "status": "pass",
        "worker_processes": workers,
        "participating_processes": participating,
        "memory_observation": memory_observation,
        "resources": resources,
        "source_fingerprint": source,
        "worker_image_attestation": image_attestation,
    }


def _connection_dsn(raw: str) -> str:
    return raw.replace("postgresql+asyncpg://", "postgresql://")


def _session_hmac_key_bytes(value: str) -> bytes:
    """Decode the session key with the same contract used by service roles.

    The service accepts an unpadded base64url/base64 value when it decodes to
    at least 32 bytes, and otherwise falls back to the raw UTF-8 value when it
    itself is at least 32 bytes.  Keeping this small pure helper local avoids
    importing CLI startup code into the acceptance gate.
    """

    raw = value.encode()
    for decoder in (base64.urlsafe_b64decode, base64.b64decode):
        try:
            candidate = decoder(value + "=" * (-len(value) % 4))
        except ValueError:
            continue
        if len(candidate) >= 32:
            return candidate
    if len(raw) < 32:
        raise ValueError("TRPC_REAL_SESSION_HMAC_KEY must decode to at least 32 bytes")
    return raw


def _envelope(
    route: BindingRoute,
    *,
    external_message_id: str,
    external_user_id: str,
    text: str,
) -> InboundEnvelope:
    return InboundEnvelope(
        channel=route.binding.channel,
        account_id=route.binding.account_id,
        external_message_id=external_message_id,
        external_user_id=external_user_id,
        conversation_kind=ConversationKind.DIRECT,
        payload_kind=PayloadKind.TEXT,
        text=text,
        occurred_at=datetime.now(UTC),
    )


async def _accept_one(
    runtime: TenantRuntime,
    binding_id: str,
    envelope: InboundEnvelope,
) -> dict[str, Any]:
    started = time.perf_counter()
    try:
        acceptance = await runtime.accept(binding_id, envelope)
    except Exception as error:  # report only the exception type
        return {
            "status": "fail",
            "latency_ms": (time.perf_counter() - started) * 1000,
            "error": _safe_failure(error),
        }
    return {
        "status": "accepted",
        "latency_ms": (time.perf_counter() - started) * 1000,
        "acceptance": acceptance,
    }


async def _submit_batch(
    runtime: TenantRuntime,
    route: BindingRoute,
    *,
    binding_id: str,
    prefix: str,
    count: int,
    offered_rate: float | None,
    max_inflight: int = DEFAULT_MAX_INFLIGHT,
    timeout_seconds: float = DEFAULT_TIMEOUT_SECONDS,
) -> dict[str, Any]:
    started = time.perf_counter()
    semaphore = asyncio.Semaphore(max(1, min(max_inflight, MAX_INFLIGHT)))
    in_flight = 0
    max_inflight = 0
    submission_start_times: list[float] = []
    submission_started_at: str | None = None
    submission_last_started_at: str | None = None

    async def scheduled(index: int) -> dict[str, Any]:
        nonlocal in_flight, max_inflight, submission_started_at, submission_last_started_at
        if offered_rate is not None:
            due = started + index / offered_rate
            delay = due - time.perf_counter()
            if delay > 0:
                await asyncio.sleep(delay)
        async with semaphore:
            submission_start_times.append(time.perf_counter())
            submission_timestamp = datetime.now(UTC).isoformat()
            if submission_started_at is None:
                submission_started_at = submission_timestamp
            submission_last_started_at = submission_timestamp
            in_flight += 1
            max_inflight = max(max_inflight, in_flight)
            try:
                return await _accept_one(
                    runtime,
                    binding_id,
                    _envelope(
                        route,
                        external_message_id=f"{prefix}-{index}",
                        external_user_id=f"{prefix}-user-{index}",
                        text=f"performance acceptance {index}",
                    ),
                )
            finally:
                in_flight -= 1

    tasks = [asyncio.create_task(scheduled(index)) for index in range(count)]
    timed_out = False
    try:
        results = await asyncio.wait_for(
            asyncio.gather(*tasks),
            timeout=timeout_seconds,
        )
    except TimeoutError:
        timed_out = True
        for task in tasks:
            task.cancel()
        await asyncio.gather(*tasks, return_exceptions=True)
        results = [
            {
                "status": "fail",
                "latency_ms": 0.0,
                "error": {"error_type": "TimeoutError"},
            }
            for _ in range(count)
        ]
    latencies = [float(item["latency_ms"]) for item in results]
    accepted = [
        item["acceptance"]
        for item in results
        if item["status"] == "accepted" and isinstance(item.get("acceptance"), Acceptance)
    ]
    errors = [item for item in results if item["status"] != "accepted"]
    elapsed = time.perf_counter() - started
    submission_span = (
        submission_start_times[-1] - submission_start_times[0]
        if len(submission_start_times) > 1
        else 0.0
    )
    actual_start_rate = _actual_start_rate(submission_start_times)
    inbound_ids = [item.inbound_id for item in accepted]
    session_ids = [item.context.session_id for item in accepted]
    return {
        "requested": count,
        "accepted": len(accepted),
        "errors": len(errors),
        "inbound_ids": inbound_ids,
        "accepted_inbound_ids": inbound_ids,
        "session_ids": session_ids,
        "unique_inbound_id_count": len(set(inbound_ids)),
        "duplicate_inbound_id_count": len(inbound_ids) - len(set(inbound_ids)),
        "unique_session_id_count": len(set(session_ids)),
        "duplicate_session_id_count": len(session_ids) - len(set(session_ids)),
        "ack_p95_ms": _percentile(latencies, 0.95),
        "ack_p50_ms": _percentile(latencies, 0.50),
        "ack_max_ms": max(latencies, default=0.0),
        "elapsed_seconds": elapsed,
        "ack_elapsed_seconds": elapsed,
        "offered_rate_per_second": (float(offered_rate) if offered_rate is not None else None),
        "callback_submission_started_at": submission_started_at,
        "submission_started_at": submission_started_at,
        "callback_submission_last_started_at": submission_last_started_at,
        "submission_span_seconds": submission_span,
        "actual_offered_start_rate_per_second": actual_start_rate,
        "actual_submission_start_rate_per_second": actual_start_rate,
        "max_inflight_accepts": max_inflight,
        "concurrency_scope": "load_generator_accept_requests",
        "agent_turn_overlap_source": "authoritative_session_turn_intervals",
        "timed_out": timed_out,
    }


