def _load_worker_parent_pid() -> int | None:
    raw = os.getenv(PARENT_PID_ENV, "").strip()
    if not raw:
        return None
    try:
        pid = int(raw)
    except ValueError:
        return None
    if pid <= 1 or pid == os.getpid():
        return None
    return pid


async def _watch_parent_process(
    parent_pid: int,
    parent_gone: asyncio.Event,
    worker_task: asyncio.Task[Any],
) -> None:
    """Cancel the load worker promptly when its supervising parent vanishes.

    Polling is intentionally used instead of a platform-specific signal or
    process handle.  It works on Windows and POSIX, and the bounded interval
    ensures an abnormal parent exit does not leave a live load generator.  A
    normal parent always cancels this task during worker cleanup.
    """

    while True:
        await asyncio.sleep(PARENT_WATCH_INTERVAL_SECONDS)
        if not _pid_alive(parent_pid):
            parent_gone.set()
            worker_task.cancel()
            return


async def _run_real(args: argparse.Namespace, preflight: dict[str, Any]) -> dict[str, Any]:
    if bool(getattr(args, "kubernetes_load_worker", False)):
        # A Kubernetes Job is supervised by its parent gate through the Job
        # lifecycle and signed handoff.  A host PID is neither meaningful nor
        # available across Pods, so never weaken the local-process watchdog;
        # this branch is reachable only after the signed evidence path passed.
        return await _run_real_once(args, preflight)
    parent_pid = _load_worker_parent_pid()
    if parent_pid is None:
        return _not_run_report(
            ["load worker parent PID is missing or invalid; refusing unsupervised execution"],
            args,
        )
    current_task = asyncio.current_task()
    if current_task is None:
        return _not_run_report(["load worker task could not be supervised safely"], args)
    parent_gone = asyncio.Event()
    watchdog = asyncio.create_task(
        _watch_parent_process(parent_pid, parent_gone, current_task),
        name="real-performance-parent-watchdog",
    )
    try:
        return await _run_real_once(args, preflight)
    except asyncio.CancelledError:
        if parent_gone.is_set():
            return _not_run_report(
                ["supervising parent disappeared; load worker canceled"],
                args,
            )
        raise
    finally:
        watchdog.cancel()
        with suppress(asyncio.CancelledError):
            await watchdog


async def _turn_rows(
    pool: asyncpg.Pool,
    tenant_id: str,
    inbound_ids: Sequence[str],
) -> list[tuple[Any, Any]]:
    if not inbound_ids:
        return []
    rows = await _scoped_fetch(
        pool,
        tenant_id,
        """
        SELECT started_at,committed_at
          FROM session_turns
         WHERE tenant_id=$1 AND inbound_id=ANY($2::uuid[])
           AND status='committed' AND committed_at IS NOT NULL
        """,
        tenant_id,
        [UUID(item) for item in inbound_ids],
    )
    return [(row["started_at"], row["committed_at"]) for row in rows]


def _normalize_json_value(value: Any) -> Any:
    """Convert non-finite floats to JSON null before strict serialization."""

    if isinstance(value, float):
        return value if math.isfinite(value) else None
    if isinstance(value, dict):
        return {key: _normalize_json_value(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_normalize_json_value(item) for item in value]
    return value


def _write_report(
    output: Path,
    report: dict[str, Any],
    *,
    args: argparse.Namespace | None = None,
    runtime_inputs: Mapping[str, Any] | None = None,
) -> None:
    # Attach this at the final write boundary as well as in the default
    # not-run constructor. This covers reports assembled by the live worker
    # path and prevents an older report from being mistaken for this candidate.
    candidate = report.get("candidate")
    candidate_run_id = candidate.get("run_id") if isinstance(candidate, Mapping) else None
    if not isinstance(candidate_run_id, str) or not candidate_run_id.strip():
        candidate_run_id = None
    if runtime_inputs is None and args is not None:
        try:
            _, stream, group = _scheduler_transport(args)
        except ValueError:
            stream = None
            group = None
        runtime_inputs = _runtime_inputs_from_report(report, stream=stream, group=group)
    if output.is_symlink() or any(
        parent.exists() and parent.is_symlink()
        for parent in (output.parent, *output.parent.parents)
    ):
        raise RuntimeError("refusing to write a performance report through a symlink")
    report["schema_version"] = REAL_PERFORMANCE_REPORT_SCHEMA_VERSION
    report["evidence"] = _evidence_metadata(
        report,
        run_id=candidate_run_id,
        runtime_inputs=runtime_inputs,
    )
    if args is not None and _live_opt_in(args):
        try:
            expected_binding = current_release_binding(required=True)
        except ValueError as error:
            binding_reasons = [str(error)]
        else:
            binding_reasons = validate_release_binding(
                report["evidence"],
                expected=expected_binding,
            )
        if binding_reasons:
            if report.get("gate") == "pass":
                report["gate"] = "not_run"
            report["production_gate"] = "not_run"
            report.setdefault("rejection_reasons", []).extend(binding_reasons)
            report.setdefault("production_rejection_reasons", []).extend(binding_reasons)
    normalized = _normalize_json_value(report)
    rendered = atomic_write_json(output, normalized)
    print(rendered, end="")


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        _apply_scheduler_transport(args)
    except ValueError as error:
        _write_report(
            args.output,
            _not_run_report([str(error)], args),
            args=args,
        )
        return 1 if args.require_production else 0
    if not _live_opt_in(args, require_worker=args.load_worker):
        _write_report(
            args.output,
            _not_run_report(_opt_in_reasons(args, require_worker=args.load_worker), args),
            args=args,
        )
        return 1 if args.require_production else 0
    missing = [name for name in REQUIRED_ENV if not os.getenv(name)]
    if missing:
        _write_report(
            args.output,
            _not_run_report(
                [f"missing required real performance environment: {name}" for name in missing],
                args,
            ),
            args=args,
        )
        return 1 if args.require_production else 0
    try:
        current_release_binding(required=True)
    except ValueError as error:
        _write_report(
            args.output,
            _not_run_report([str(error)], args),
            args=args,
        )
        return 1 if args.require_production else 0
    try:
        preflight = _preflight_for_execution(args)
    except ValueError as error:
        preflight = {"status": "not_run", "reason": str(error)}
    if preflight["status"] != "pass":
        report = {
            "baseline": {
                "sustained_callbacks": DEFAULT_CALLBACKS,
                "offered_callback_rate_per_second": DEFAULT_CALLBACK_RATE,
                "callback_ack_p95_ms_max": DEFAULT_P95_MS,
                "concurrent_turns": DEFAULT_BURST_TURNS,
                "concurrent_turns_definition": (
                    "maximum overlap of authoritative committed session_turn intervals"
                ),
                "accepted_message_loss_max": 0,
                "burst_queue_pending_delta_max": 0,
            },
            "candidate": {
                "mode": "real_postgresql_redis_multiprocess",
                "preflight": preflight,
                "parameters": _run_parameters(args),
            },
            "case_deltas": {},
            "gate": preflight["status"],
            "production_gate": "not_run",
            "rejection_reasons": [str(preflight.get("reason", "performance preflight failed"))],
            "production_rejection_reasons": [
                str(preflight.get("reason", "performance preflight failed"))
            ],
        }
        _write_report(args.output, report, args=args)
        return 1 if args.require_production else 0
    report = (
        asyncio.run(_run_real(args, preflight))
        if args.load_worker
        else _run_external_load(args, preflight)
    )
    _write_report(args.output, report, args=args)
    return (
        0
        if report.get("gate") == "pass"
        and (not args.require_production or report.get("production_gate") == "pass")
        else 1
    )


